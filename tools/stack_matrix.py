PICKED_BANNER = "Этот инструмент ничего не выбирает. Он даёт вопросы и оси " \
                "сравнения; решение вам придётся отстоять письменно."


def load_brief(args):
    brief = {}
    if args.brief:
        p = Path(args.brief)
        if not p.is_file():
            raise ValueError("файл брифа не найден: %s" % args.brief)
        for raw in p.read_text(encoding="utf-8", errors="replace").splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if "=" not in line:
                continue
            k, v = line.split("=", 1)
            brief[k.strip().lower()] = v.strip()
    for item in args.set or []:
        if "=" not in item:
            raise ValueError("--set ожидает KEY=VALUE, получено: %s" % item)
        k, v = item.split("=", 1)
        brief[k.strip().lower()] = v.strip()
    return brief


def select_layers(brief):
    if not brief:
        return list(LAYERS)
    present = set()
    for key in brief:
        for layer in LAYERS:
            if key in BRIEF_HINT.get(layer["id"], []):
                present.add(layer["id"])
    if not present:
        return list(LAYERS)
    return [l for l in LAYERS if l["id"] in present]


class Out(object):
    """Console writer that can never raise UnicodeEncodeError."""

    def __init__(self, stream):
        self.stream = stream

    def write(self, text):
        try:
            self.stream.write(text)
        except UnicodeEncodeError:
            enc = getattr(self.stream, "encoding", None) or "ascii"
            self.stream.write(text.encode(enc, "replace").decode(enc, "replace"))

    def line(self, text=""):
        self.write(text + "\n")


def report(layers, brief, out, full):
    out.line("матрица решений по стеку - только вопросы, без вердикта")
    out.line(PICKED_BANNER)
    if full:
        out.line("выбор слоев: все %d обязательных слоев" % len(layers))
    else:
        out.line("выбор слоев: ключи брифа отметили как релевантные %d слоев"
                 % len(layers))
    out.line("")
    if brief:
        out.line("бриф (как дан, без интерпретации):")
        for k in sorted(brief):
            out.line("  %s = %s" % (k, brief[k]))
    else:
        out.line("бриф не задан, поэтому печатается полный список "
                 "обязательных слоев и ни один слой не отфильтрован по "
                 "релевантности")
    out.line("")
    for i, layer in enumerate(layers, 1):
        out.line("%2d. %s [%s]" % (i, layer["title"], layer["id"]))
        out.line("    решающий вопрос / deciding question: %s"
                 % layer["deciding_question"])
        out.line("    что это решит / what would settle it: %s"
                 % layer["evidence"])
        out.line("    comparison axes (взвешивайте их, в таком порядке для "
                 "этого проекта):")
        for a in layer["axes"]:
            out.line("      - %s" % a)
        out.line("    кандидаты (каждая строка - это компромисс, а не "
                 "предпочтение):")
        for opt in layer["options"]:
            out.line("      * %s" % opt["option"])
            out.line("          %s" % opt["tradeoff"])
        out.line("")
    out.line("дальше: письменно ответьте на каждый решающий вопрос выше и по "
             "каждому слою зафиксируйте отклонённые варианты. Инструмент "
             "doctor валит дизайн, в котором нет ни одной отклонённой "
             "альтернативы.")


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="stack_matrix.py",
        description="Печатает матрицу решений по обязательным слоям "
                    "инфраструктуры: кандидаты, решающий вопрос и данные, "
                    "которые его решат. Явного фаворита инструмент не "
                    "называет, это сознательный принцип.",
    )
    ap.add_argument("--brief", help="путь к файлу брифа KEY=VALUE "
                                     "(комментарии с # разрешены)")
    ap.add_argument("--set", action="append", metavar="KEY=VALUE",
                    help="добавить один ключ брифа, можно повторять")
    ap.add_argument("--layers", default="",
                    help="идентификаторы слоев через запятую (по умолчанию "
                         "все, либо отфильтрованные по релевантности брифа, "
                         "если бриф задан)")
    ap.add_argument("--list-layers", action="store_true",
                    help="напечатать идентификаторы слоев и выйти с кодом 0")
    ap.add_argument("--json", action="store_true",
                    help="машиночитаемый вывод")
    args = ap.parse_args(argv)

    out = Out(sys.stdout)
    if args.list_layers:
        if args.json:
            out.line(json.dumps(
                {"tool": "stack_matrix", "schema": SCHEMA,
                 "layers": [{"id": l["id"], "title": l["title"]}
                            for l in LAYERS]},
                ensure_ascii=True))
        else:
            for l in LAYERS:
                out.line("%-14s %s" % (l["id"], l["title"]))
        return 0

    try:
        brief = load_brief(args)
    except ValueError as exc:
        if args.json:
            out.line(json.dumps({"tool": "stack_matrix", "schema": SCHEMA,
                                 "ok": False, "error": str(exc),
                                 "layers": []}, ensure_ascii=True))
        else:
            out.line("[FAIL] " + str(exc))
        return 2

    layers = select_layers(brief)
    full = True
    if args.layers:
        wanted = [x.strip().lower() for x in args.layers.split(",")
                  if x.strip()]
        known = set(l["id"] for l in LAYERS)
        unknown = [w for w in wanted if w not in known]
        if unknown:
            msg = "неизвестные идентификаторы слоев: %s (используйте --list-layers)" \
                % ", ".join(unknown)
            if args.json:
                out.line(json.dumps({"tool": "stack_matrix", "schema": SCHEMA,
                                     "ok": False, "error": msg,
                                     "layers": []}, ensure_ascii=True))
            else:
                out.line("[FAIL] " + msg)
            return 2
        layers = [l for l in LAYERS if l["id"] in wanted]
        full = len(layers) == len(LAYERS)
    elif brief:
        full = len(layers) == len(LAYERS)

    if not layers:
        msg = "фильтр по слоям ничего не выбрал"
        if args.json:
            out.line(json.dumps({"tool": "stack_matrix", "schema": SCHEMA,
                                 "ok": False, "error": msg, "layers": []},
                                ensure_ascii=True))
        else:
            out.line("[FAIL] " + msg)
        return 2

    if args.json:
        out.line(json.dumps(
            {
                "tool": "stack_matrix",
                "schema": SCHEMA,
                "ok": True,
                "declares_winner": False,
                "brief": brief,
                "layer_count": len(layers),
                "layers": [
                    {
                        "id": l["id"],
                        "title": l["title"],
                        "deciding_question": l["deciding_question"],
                        "evidence_that_settles_it": l["evidence"],
                        "axes": l["axes"],
                        "options": l["options"],
                    } for l in layers
                ],
            }, ensure_ascii=True, indent=2))
    else:
        report(layers, brief, out, full)
    return 0


if __name__ == "__main__":
    sys.exit(main())
